function renderPostNav(prev, next) {
  if (!prev && !next) return '';
  const parts = ['      <nav class="post-nav" aria-label="More posts">'];
  if (prev) {
    parts.push(
      '        <a class="post-nav-link post-nav-prev" href="' + xmlEscape(postUrl(prev.slug)) + '" rel="prev">' +
        '<span class="post-nav-label">← Older</span>' +
        '<span class="post-nav-title">' + xmlEscape(prev.title) + '</span></a>'
    );
  }
  if (next) {
    parts.push(
      '        <a class="post-nav-link post-nav-next" href="' + xmlEscape(postUrl(next.slug)) + '" rel="next">' +
        '<span class="post-nav-label">Newer →</span>' +
        '<span class="post-nav-title">' + xmlEscape(next.title) + '</span></a>'
    );
  }
  parts.push('      </nav>');
  return parts.join('\n');
}

