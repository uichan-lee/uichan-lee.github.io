// ─── Main ───────────────────────────────────────────────────────────────────

function build() {
  const loaded = loadWritings();
  const writings = loaded.writings || [];
  const categories = loaded.writingCategories || {};

  // Same guard as sync.js uses for the feeds: a run that collected nothing
  // (js/writings.js missing or emptied) must never wipe the published pages.
  if (writings.length === 0) {
    console.log('  skip build: js/writings.js lists no posts');
    return 0;
  }

  // Newest first. Index i-1 is the newer neighbour, i+1 the older one.
  const posts = writings.slice().sort(function (a, b) {
    return String(b.date).localeCompare(String(a.date));
  });

  const searchIndex = {};
  posts.forEach(function (post) {
    const mdPath = path.join(ROOT, post.file);
    let plain = '';
    if (fs.existsSync(mdPath)) {
      plain = stripMarkdownToPlainText(fs.readFileSync(mdPath, 'utf-8'));
    } else {
      console.warn('  warning: markdown missing for ' + post.slug + ' (' + post.file + ')');
    }
    post.readingTime = readingTimeMinutes(plain);
    searchIndex[post.slug] = { title: post.title, text: plain };
  });

  fs.rmSync(PAGES_DIR, { recursive: true, force: true });
  fs.mkdirSync(PAGES_DIR, { recursive: true });

  posts.forEach(function (post, i) {
    const dir = path.join(PAGES_DIR, post.slug);
    fs.mkdirSync(dir, { recursive: true });
    const html = renderPostPage(
      post,
      categories[post.category] || post.category || '',
      posts[i + 1] || null, // older
      posts[i - 1] || null  // newer
    );
    fs.writeFileSync(path.join(dir, 'index.html'), html, 'utf-8');
  });
  console.log('  p/<slug>/index.html: ' + posts.length + ' pages written');

  fs.writeFileSync(SEARCH_INDEX_JSON, JSON.stringify(searchIndex), 'utf-8');
  console.log('  search-index.json: ' + Object.keys(searchIndex).length + ' entries');

  writeFeeds(ROOT, SITE_URL, posts, categories);
  console.log('  sitemap.xml + feed.xml written');

  return posts.length;
}

module.exports = { build, stripMarkdownToPlainText, readingTimeMinutes, postUrl };

if (require.main === module) {
  console.log('Building post pages from js/writings.js...\n');
  build();
  console.log('\nDone.');
}
