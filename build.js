#!/usr/bin/env node
//
// Generates everything that is derived from the post list:
//
//   p/<slug>/index.html   one real page per post (crawlable, shareable)
//   js/search-index.json  full-text index, fetched on demand by main.js
//   sitemap.xml, feed.xml via feeds.js
//
// Deliberately reads only what is committed to this repo — js/writings.js and
// posts/**/*.md — and never Ricky's Obsidian vault. sync.js owns the vault and
// writes js/writings.js + posts/; this file turns that into the published site.
// Keeping the two separate means the site can be rebuilt from a fresh clone,
// by CI or by anyone, without the vault being present.
//
// Runnable standalone (`node build.js`) or via sync.js, which calls build()
// after it has refreshed js/writings.js.

const fs = require('fs');
const path = require('path');
const { writeFeeds } = require('./feeds');

const SITE_URL = 'https://uichan-lee.github.io';
const AUTHOR = 'Uichan Lee';

const ROOT = __dirname;
const WRITINGS_JS = path.join(ROOT, 'js', 'writings.js');
const SEARCH_INDEX_JSON = path.join(ROOT, 'js', 'search-index.json');
const PAGES_DIR = path.join(ROOT, 'p');

// ─── Helpers ────────────────────────────────────────────────────────────────

function xmlEscape(s) {
  return String(s == null ? '' : s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

/** JSON embedded in <script> must not contain a literal </script> or a raw <. */
function jsonForScript(value) {
  return JSON.stringify(value).replace(/</g, '\\u003c');
}

/**
 * Read js/writings.js and hand back the two globals it declares.
 * That file is generated by sync.js as plain `const writings = [...]`, so it
 * is evaluated rather than parsed. It is our own build output, not input from
 * anywhere untrusted.
 */
function loadWritings() {
  const code = fs.readFileSync(WRITINGS_JS, 'utf-8');
  const out = {};
  new Function(
    'out',
    code + '\nout.writings = writings; out.writingCategories = writingCategories;'
  )(out);
  return out;
}

/** Strip markdown to plain text, for the search index and the word count. */
function stripMarkdownToPlainText(content) {
  const text = content
    .replace(/^---[\s\S]*?^---\s*/m, '')
    .replace(/```[\s\S]*?```/g, ' ')
    .replace(/!\[\[[^\]]*\]\]/g, ' ')
    .replace(/!\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/\*\*?|__?/g, '')
    .replace(/^#{1,6}\s+/gm, ' ')
    .replace(/^\s*[-*]\s+/gm, ' ')
    .replace(/^\s*\d+\.\s+/gm, ' ')
    .replace(/^\s*\|.*\|\s*$/gm, ' ')
    .replace(/\$\$[\s\S]*?\$\$/g, ' ')
    .replace(/\$[^$]+\$/g, ' ')
    .replace(/\n+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  return text.length > 30000 ? text.slice(0, 30000) : text;
}

const CJK_RE = /[ㄱ-힝一-鿿぀-ヿ]/g;

/**
 * Minutes to read. Latin text is counted in words at 200 wpm; Korean and other
 * CJK is counted in characters at 500 cpm, because whitespace-splitting Hangul
 * badly undercounts it (these posts are a mix of both).
 */
function readingTimeMinutes(plain) {
  const cjk = (plain.match(CJK_RE) || []).length;
  const latin = plain.replace(CJK_RE, ' ').split(/\s+/).filter(Boolean).length;
  return Math.max(1, Math.ceil(latin / 200 + cjk / 500));
}

function formatDisplayDate(dateStr) {
  if (!dateStr) return '';
  const d = new Date(dateStr + 'T00:00:00Z');
  if (Number.isNaN(d.getTime())) return '';
  return d.toLocaleDateString('en-US', {
    year: 'numeric', month: 'long', day: 'numeric', timeZone: 'UTC',
  });
}

/** Slugs contain Hangul, so every generated href has to be percent-encoded. */
function postUrl(slug) {
  return '/p/' + encodeURIComponent(slug) + '/';
}

